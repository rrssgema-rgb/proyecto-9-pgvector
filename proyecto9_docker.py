
import os
import json
import psycopg
from psycopg import sql
from pgvector.psycopg import register_vector
from sentence_transformers import SentenceTransformer


# ============================================================
# PROYECTO 9 - POSTGRESQL, PGVECTOR Y AISLAMIENTO DE TENANTS
# ============================================================

HOST = "localhost"
PORT = 5433
DATABASE = "proyecto9"
ADMIN_USER = "alumno"
APP_USER = "app_pgvector"

TENANT_A = "aseguradora_A"
TENANT_B = "aseguradora_B"

MODELO_EMBEDDINGS = (
    "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
)

FRASES_A = [
    "Quiero dar parte de un accidente de coche.",
    "Necesito asistencia en carretera porque mi coche no arranca.",
    "Quiero consultar la fecha de vencimiento de mi póliza.",
    "Necesito información sobre el pago de un recibo del seguro.",
    "Quiero saber qué documentos necesito para contratar un seguro.",
]

FRASE_PRUEBA_B = (
    "Quiero consultar una factura de reparación de mi vehículo."
)

CONSULTA = "Mi vehículo se ha averiado y necesito ayuda"


def conectar(usuario, contrasena):
    """Abre una conexión con PostgreSQL en Docker."""
    return psycopg.connect(
        host=HOST,
        port=PORT,
        dbname=DATABASE,
        user=usuario,
        password=contrasena,
    )


def preparar_base_de_datos():
    """Crea la tabla, los índices, la política RLS y el usuario."""

    print("\n1. PREPARANDO POSTGRESQL Y PGVECTOR")

    conn = conectar(ADMIN_USER, os.environ["PGPASSWORD"])

    try:
        with conn.cursor() as cur:
            cur.execute("CREATE EXTENSION IF NOT EXISTS vector;")

            cur.execute("""
                CREATE TABLE IF NOT EXISTS frases_vectores (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id TEXT NOT NULL,
                    frase TEXT NOT NULL,
                    embedding VECTOR(384) NOT NULL
                );
            """)

            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_frases_vectores_tenant
                ON frases_vectores (tenant_id);
            """)

            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_frases_vectores_embedding_hnsw
                ON frases_vectores
                USING hnsw (embedding vector_cosine_ops);
            """)

            # Crear un usuario de aplicación sin privilegios de superusuario.
            cur.execute("""
                DO $$
                BEGIN
                    IF NOT EXISTS (
                        SELECT 1 FROM pg_roles
                        WHERE rolname = 'app_pgvector'
                    ) THEN
                        CREATE ROLE app_pgvector
                        LOGIN NOSUPERUSER NOCREATEDB
                        NOCREATEROLE NOINHERIT NOBYPASSRLS;
                    END IF;
                END
                $$;
            """)

            cur.execute(
                sql.SQL("ALTER ROLE app_pgvector WITH PASSWORD {}").format(
                    sql.Literal(os.environ["APP_ROLE_PASSWORD"])
                )
            )

            cur.execute("""
                GRANT CONNECT ON DATABASE proyecto9 TO app_pgvector;
                GRANT USAGE ON SCHEMA public TO app_pgvector;
                GRANT SELECT, INSERT, UPDATE, DELETE
                ON TABLE public.frases_vectores TO app_pgvector;
                GRANT USAGE, SELECT
                ON ALL SEQUENCES IN SCHEMA public TO app_pgvector;
            """)

            # Activar el aislamiento por filas.
            cur.execute("""
                ALTER TABLE public.frases_vectores
                ENABLE ROW LEVEL SECURITY;
            """)

            cur.execute("""
                ALTER TABLE public.frases_vectores
                FORCE ROW LEVEL SECURITY;
            """)

            cur.execute("""
                DROP POLICY IF EXISTS aislamiento_tenant
                ON public.frases_vectores;
            """)

            cur.execute("""
                CREATE POLICY aislamiento_tenant
                ON public.frases_vectores
                FOR ALL
                USING (
                    tenant_id = NULLIF(
                        current_setting('app.tenant_id', true), ''
                    )
                )
                WITH CHECK (
                    tenant_id = NULLIF(
                        current_setting('app.tenant_id', true), ''
                    )
                );
            """)

        conn.commit()

        print("Tabla, índices y política RLS preparados.")
        print("Usuario de aplicación configurado.")

        # Registrar el tipo VECTOR una vez creada la extensión.
        register_vector(conn)

        modelo = SentenceTransformer(MODELO_EMBEDDINGS)

        embedding_a = modelo.encode(FRASES_A)
        embedding_b = modelo.encode([FRASE_PRUEBA_B])[0]

        # Reemplazar los datos de prueba para evitar duplicados.
        with conn.cursor() as cur:
            cur.execute(
                "DELETE FROM frases_vectores WHERE tenant_id IN (%s, %s);",
                (TENANT_A, TENANT_B),
            )

            for frase, embedding in zip(FRASES_A, embedding_a):
                cur.execute("""
                    INSERT INTO frases_vectores
                        (tenant_id, frase, embedding)
                    VALUES (%s, %s, %s);
                """, (TENANT_A, frase, embedding))

            cur.execute("""
                INSERT INTO frases_vectores
                    (tenant_id, frase, embedding)
                VALUES (%s, %s, %s);
            """, (TENANT_B, FRASE_PRUEBA_B, embedding_b))

        conn.commit()
        print("Cinco frases guardadas para A y una para B.")

        return modelo

    finally:
        conn.close()


def comprobar_aislamiento():
    """Comprueba que RLS impide ver los datos de otros tenants."""

    print("\n2. COMPROBANDO AISLAMIENTO ENTRE TENANTS")

    conn = conectar(APP_USER, os.environ["APP_ROLE_PASSWORD"])

    try:
        with conn.cursor() as cur:
            for tenant, esperado in [
                (TENANT_A, 5),
                (TENANT_B, 1),
            ]:
                cur.execute(
                    "SELECT set_config('app.tenant_id', %s, false);",
                    (tenant,),
                )

                # No se incluye WHERE tenant_id: RLS debe filtrar los datos.
                cur.execute("SELECT tenant_id, frase FROM frases_vectores;")
                filas = cur.fetchall()

                if len(filas) != esperado:
                    raise RuntimeError(
                        f"Error de aislamiento para {tenant}: "
                        f"se esperaban {esperado} filas y llegaron {len(filas)}."
                    )

                if any(fila[0] != tenant for fila in filas):
                    raise RuntimeError(
                        f"FALLO DE SEGURIDAD: {tenant} ve datos ajenos."
                    )

                print(f"{tenant}: {len(filas)} filas visibles. AISLAMIENTO OK")

            cur.execute("SELECT set_config('app.tenant_id', '', false);")
            cur.execute("SELECT COUNT(*) FROM frases_vectores;")
            sin_tenant = cur.fetchone()[0]

            if sin_tenant != 0:
                raise RuntimeError(
                    "FALLO DE SEGURIDAD: hay datos visibles sin tenant."
                )

            print("Sin tenant: 0 filas visibles. AISLAMIENTO OK")

    finally:
        conn.close()


def buscar_frases(modelo):
    """Recupera las dos frases más similares del tenant autorizado."""

    print("\n3. BUSQUEDA SEMANTICA")

    embedding_consulta = modelo.encode(CONSULTA)

    conn = conectar(APP_USER, os.environ["APP_ROLE_PASSWORD"])

    try:
        register_vector(conn)

        with conn.cursor() as cur:
            cur.execute(
                "SELECT set_config('app.tenant_id', %s, false);",
                (TENANT_A,),
            )

            cur.execute("""
                SELECT frase, embedding <=> %s AS distancia
                FROM frases_vectores
                WHERE tenant_id = %s
                ORDER BY embedding <=> %s
                LIMIT 2;
            """, (embedding_consulta, TENANT_A, embedding_consulta))

            resultados = cur.fetchall()

        print("Consulta:", CONSULTA)
        print("Tenant:", TENANT_A)
        print("\nLas dos frases más similares:")

        if len(resultados) != 2:
            raise RuntimeError("La búsqueda no ha devuelto dos frases.")

        for posicion, (frase, distancia) in enumerate(resultados, start=1):
            print(f"{posicion}. {frase}")
            print(f"   Distancia coseno: {distancia:.4f}")

        print("BUSQUEDA CORRECTA")

    finally:
        conn.close()


def medir_rendimiento(modelo):
    """Mide el tiempo de ejecución de la consulta SQL."""

    print("\n4. MEDICION DE RENDIMIENTO")

    embedding_consulta = modelo.encode(CONSULTA)

    conn = conectar(APP_USER, os.environ["APP_ROLE_PASSWORD"])

    try:
        register_vector(conn)

        with conn.cursor() as cur:
            cur.execute(
                "SELECT set_config('app.tenant_id', %s, false);",
                (TENANT_A,),
            )

            cur.execute("""
                EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON)
                SELECT frase, embedding <=> %s AS distancia
                FROM frases_vectores
                WHERE tenant_id = %s
                ORDER BY embedding <=> %s
                LIMIT 2;
            """, (embedding_consulta, TENANT_A, embedding_consulta))

            plan = cur.fetchone()[0]

            if isinstance(plan, str):
                plan = json.loads(plan)

            datos = plan[0]
            print(f"Tiempo de planificación: "
                  f"{datos['Planning Time']:.3f} ms")
            print(f"Tiempo de ejecución SQL: "
                  f"{datos['Execution Time']:.3f} ms")

    finally:
        conn.close()


def main():
    # Las contraseñas se leen del entorno y no se guardan en el archivo.
    if not os.environ.get("PGPASSWORD"):
        raise RuntimeError(
            "Falta PGPASSWORD. Configúrala en PowerShell antes de ejecutar."
        )

    if not os.environ.get("APP_ROLE_PASSWORD"):
        raise RuntimeError(
            "Falta APP_ROLE_PASSWORD. Configúrala en PowerShell antes de ejecutar."
        )

    modelo = preparar_base_de_datos()
    comprobar_aislamiento()
    buscar_frases(modelo)
    medir_rendimiento(modelo)

    print("\nPROYECTO 9: EJECUCION COMPLETADA CORRECTAMENTE")


if __name__ == "__main__":
    main()
